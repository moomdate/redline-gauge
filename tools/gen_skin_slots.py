#!/usr/bin/env python3
"""Make the DATA WAVE / RACE CODE value slots selectable.

The mockups bake each slot's label, icon and unit into the plate. This removes them (inpaint at
320x240) so firmware can draw whatever value the slot is set to, and extracts the icons as
sprites (src/assets/skin_icons.h) to draw back when the slot holds a matching value.

Inputs (never modified, so this is re-runnable):
  tools/art/datawave_plate_labels.png   DATA WAVE plate with labels
  tools/art/racecode_plate.png          RACE CODE plate as written by gen_racecode_plate.py
Outputs:
  src/assets/bg_datawave.h, bg_racecode array inside src/assets/bg_racecode.h, src/assets/skin_icons.h
Run after gen_racecode_plate.py:  python tools/gen_skin_slots.py
"""
import re
import numpy as np, cv2
from PIL import Image

def to565(p):
    return ((int(p[0]) >> 3) << 11) | ((int(p[1]) >> 2) << 5) | (int(p[2]) >> 3)

def arr_lines(name, a):
    flat = [to565(p) for p in a.reshape(-1, 3)]
    out = [f"static const uint16_t {name}[{len(flat)}] = {{"]
    for i in range(0, len(flat), 16):
        out.append("  " + ",".join("0x%04X" % v for v in flat[i:i + 16]) + ",")
    out.append("};")
    return out

def strip(img, rects):
    """rects: (x0, y0, x1, y1, thresh) -- pixels brighter than thresh (max channel) are removed."""
    mask = np.zeros(img.shape[:2], np.uint8)
    for x0, y0, x1, y1, th in rects:
        m = (img[y0:y1, x0:x1].max(-1) > th).astype(np.uint8) * 255
        mask[y0:y1, x0:x1] |= cv2.dilate(m, np.ones((3, 3), np.uint8))
    return cv2.inpaint(np.ascontiguousarray(img), mask, 3, cv2.INPAINT_TELEA)

# ---- DATA WAVE ---------------------------------------------------------------------------------
dw = np.asarray(Image.open("tools/art/datawave_plate_labels.png").convert("RGB"))
DW_STRIP = [
    (132, 75, 160, 87, 40),   # row 1 label (TPS)
    (177, 75, 199, 85, 60),   # row 1 stripes
    (119, 115, 146, 126, 40), # row 2 label (AFR)
    (158, 113, 180, 124, 60), # row 2 stripes
    (132, 152, 160, 164, 40), # row 3 label (ECT)
    (166, 151, 186, 162, 60), # row 3 stripes
    (102, 157, 127, 183, 45), # row 3 thermometer
    (160, 164, 181, 181, 40), # row 3 °C
    (5, 206, 28, 226, 70),    # checkered flag (LAP)
    (31, 208, 53, 221, 40),   # LAP
    (102, 208, 128, 221, 40), # BEST
]
dw_clean = strip(dw, DW_STRIP)
Image.fromarray(dw_clean).save("tools/art/datawave_plate.png")
lines = ["// bg_datawave: DATA WAVE plate (mockup with the live data and slot labels removed).",
         "// Generated by tools/gen_skin_slots.py, do not edit.",
         "#pragma once", "#include <stdint.h>", ""]
lines += arr_lines("bg_datawave", dw_clean).copy()
lines[5] = lines[5].replace("[76800]", "[320 * 240]")
open("src/assets/bg_datawave.h", "w").write("\n".join(lines) + "\n")

# ---- RACE CODE ---------------------------------------------------------------------------------
rc = np.asarray(Image.open("tools/art/racecode_plate.png").convert("RGB"))
RC_STRIP = [
    (45, 56, 67, 68, 50),     # OIL
    (9, 62, 42, 79, 60),      # oil can
    (63, 68, 82, 85, 50),     # °C
    (42, 98, 69, 112, 50),    # ECT
    (13, 99, 39, 128, 60),    # thermometer
    (61, 112, 79, 128, 50),   # °C
    (46, 143, 74, 157, 50),   # BAT
    (13, 148, 43, 171, 70),   # battery
    (76, 156, 91, 174, 50),   # v
]
rc_clean = strip(rc, RC_STRIP)
Image.fromarray(rc_clean).save("tools/art/racecode_plate_slots.png")
h = open("src/assets/bg_racecode.h").read()
new = "\n".join(arr_lines("bg_racecode", rc_clean))
h, n = re.subn(r"static const uint16_t bg_racecode\[\d+\] = \{.*?\};", lambda m: new, h, count=1, flags=re.S)
assert n == 1
open("src/assets/bg_racecode.h", "w").write(h)

# ---- icon sprites ------------------------------------------------------------------------------
ICONS = [  # name, source image, x, y, w, h
    ("icon_oil",     rc, 10, 63, 31, 15),
    ("icon_therm",   rc, 13, 100, 25, 27),
    ("icon_batt",    rc, 14, 149, 28, 21),
    ("icon_therm_s", dw, 103, 158, 23, 24),
]
out = ["// Slot icons cut from the skin mockups. Generated by tools/gen_skin_slots.py, do not edit.",
       "// Drawn keyed: only pixels brighter than the tile background are copied.",
       "#pragma once", "#include <stdint.h>", "",
       "struct SkinIcon { int w, h; const uint16_t *px; };", ""]
SCALE = {"icon_oil": 0.8, "icon_therm": 0.72, "icon_batt": 0.8, "icon_therm_s": 1.0}   # RACE CODE tiles are tight
for name, img, x, y, w, hh in ICONS:
    sp = img[y:y + hh, x:x + w]
    k = SCALE[name]
    if k != 1.0:
        w, hh = max(1, round(w * k)), max(1, round(hh * k))
        sp = np.asarray(Image.fromarray(sp).resize((w, hh), Image.LANCZOS))
    out += arr_lines(name + "_px", sp)
    out.append(f"static const SkinIcon {name} = {{ {w}, {hh}, {name}_px }};")
    out.append("")
# ---- drawn icons for the other items (neon line style of the mockup's icons) -------------------
from PIL import ImageDraw, ImageFilter, ImageFont
Z = 4                                           # supersampling
def neon(name, w, h, color, draw_fn):
    W, H = w * Z, h * Z
    m = Image.new("L", (W, H), 0)
    draw_fn(ImageDraw.Draw(m), W, H)
    glow = m.filter(ImageFilter.GaussianBlur(Z * 1.2))
    col = np.array(color, float)
    a = np.asarray(m, float) / 255.0
    g = np.asarray(glow, float) / 255.0 * 0.55
    rgb = col * np.clip(a + g, 0, 1)[..., None] + 255 * (a * 0.25)[..., None]   # hot core
    img = Image.fromarray(np.clip(rgb, 0, 255).astype(np.uint8)).resize((w, h), Image.LANCZOS)
    o = arr_lines(name + "_px", np.asarray(img))
    o.append(f"static const SkinIcon {name} = {{ {w}, {h}, {name}_px }};")
    o.append("")
    return o

LW = int(Z * 1.6)
FONT = "/Library/Fonts/Arial Unicode.ttf"
def txt(text, size):
    def f(d, W, H):
        fnt = ImageFont.truetype(FONT, int(size * Z))
        d.text((W / 2, H / 2), text, fill=255, font=fnt, anchor="mm")
    return f
def tps(d, W, H):      # throttle butterfly
    r = min(W, H) / 2 - LW
    cx, cy = W / 2, H / 2
    d.ellipse([cx - r, cy - r, cx + r, cy + r], outline=255, width=LW)
    d.line([cx - r * 0.75, cy + r * 0.75, cx + r * 0.75, cy - r * 0.75], fill=255, width=LW)
    d.ellipse([cx - LW, cy - LW, cx + LW, cy + LW], fill=255)
def mapg(d, W, H):     # pressure gauge
    r = W / 2 - LW
    cx, cy = W / 2, H * 0.78
    d.arc([cx - r, cy - r, cx + r, cy + r], 180, 360, fill=255, width=LW)
    import math
    for k in range(5):
        t = math.radians(180 + k * 45)
        d.line([cx + (r - 3 * Z) * math.cos(t), cy + (r - 3 * Z) * math.sin(t),
                cx + r * math.cos(t), cy + r * math.sin(t)], fill=255, width=max(1, LW // 2))
    t = math.radians(305)
    d.line([cx, cy, cx + (r - 4 * Z) * math.cos(t), cy + (r - 4 * Z) * math.sin(t)], fill=255, width=LW)
    d.ellipse([cx - LW * 1.3, cy - LW * 1.3, cx + LW * 1.3, cy + LW * 1.3], fill=255)
def pump(d, W, H):     # fuel pump
    d.rounded_rectangle([W * 0.12, H * 0.08, W * 0.62, H * 0.92], radius=Z, outline=255, width=LW)
    d.rectangle([W * 0.22, H * 0.2, W * 0.52, H * 0.42], fill=255)
    d.line([W * 0.62, H * 0.3, W * 0.82, H * 0.42, W * 0.82, H * 0.78, W * 0.92, H * 0.78], fill=255, width=LW, joint="curve")
def drop(d, W, H):     # fuel drop
    cx = W / 2; r = W * 0.3
    d.polygon([(cx, H * 0.06), (cx - r * 0.95, H * 0.62), (cx + r * 0.95, H * 0.62)], fill=255)
    d.ellipse([cx - r, H * 0.94 - 2 * r, cx + r, H * 0.94], fill=255)
def bars(d, W, H):     # engine load
    for k in range(4):
        x0 = W * (0.1 + k * 0.22); top = H * (0.7 - k * 0.2)
        d.rectangle([x0, top, x0 + W * 0.14, H * 0.92], fill=255)
def bolt(d, W, H):     # ignition
    d.polygon([(W * 0.58, H * 0.04), (W * 0.18, H * 0.56), (W * 0.46, H * 0.56), (W * 0.36, H * 0.96),
               (W * 0.82, H * 0.4), (W * 0.54, H * 0.4)], fill=255)
CYAN, AMBER, RED, YEL = (40, 200, 255), (255, 150, 30), (255, 50, 40), (255, 210, 40)
out += neon("icon_tps",  20, 20, CYAN,  tps)
out += neon("icon_afr",  20, 20, AMBER, txt("λ", 17))
out += neon("icon_map",  22, 16, CYAN,  mapg)
out += neon("icon_fuel", 18, 20, YEL,   pump)
out += neon("icon_rate", 16, 20, YEL,   drop)
out += neon("icon_load", 20, 18, RED,   bars)
out += neon("icon_ign",  16, 20, YEL,   bolt)
out += neon("icon_o2",   22, 18, CYAN,  txt("O₂", 13))
out += neon("icon_trim", 18, 18, CYAN,  txt("±", 18))
open("src/assets/skin_icons.h", "w").write("\n".join(out))
print("ok")
