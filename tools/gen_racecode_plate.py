#!/usr/bin/env python3
"""RACE CODE skin artwork -> src/assets/bg_racecode.h

From the full-resolution mockup:
  1. inpaint the live data away (values, clock, gear, SPORT) at full resolution,
  2. downscale to 320x240,
  3. 'unlit' plate  = the lit rev arc darkened to an off track,
     'lit' band     = the arc fully lit over the whole sweep (mockup pixels where the mockup
                      has them, the low-rpm end continued from the mockup's own segments).
Firmware composites unlit plate + lit band up to the current rpm angle.

Needs opencv + numpy + Pillow (run on the Mac, not part of the build):
  python tools/gen_racecode_plate.py <mockup.png>
"""
import sys, math
import numpy as np, cv2
from PIL import Image

SRC = sys.argv[1]
OUT_H = "src/assets/bg_racecode.h"
CX, CY = 192.3, 104.9          # rev-arc centre (fitted to the lit band, 320x240 coords)
R_IN, R_OUT = 74, 112          # band radii incl. glow (track centre runs r 84..100)
A0, A1 = -136.0, 131.0         # sweep: numeral 0 -> numeral 9 (deg, 0 = up, clockwise +)
A_LIT = -34.0                  # mockup's lit arc starts here; below it is synthesised

full = np.asarray(Image.open(SRC).convert("RGB"))
H, W = full.shape[:2]
s = W / 320.0

# ---- 1. live data masks (320 coords) -----------------------------------------------------------
def kind_mask(img, k):
    r, g, b = [img[..., i].astype(int) for i in range(3)]
    if k == "white":  return np.minimum(np.minimum(r, g), b) > 105
    if k == "bright": return np.maximum(np.maximum(r, g), b) > 70
    if k == "red":    return (r > 140) & (r > g + 60)
    if k == "all":    return np.ones(r.shape, bool)
    raise ValueError(k)

MASKS = [  # x0, y0, x1, y1, kind, dilate
    (42, 66, 66, 83, "bright", 7),      # OIL 92
    (39, 112, 63, 128, "bright", 7),    # ECT 88
    (44, 157, 80, 173, "bright", 5),    # BAT 14.2
    (52, 193, 98, 207, "white", 7),    # TRIP 128.4
    (262, 7, 313, 24, "white", 7),     # clock
    (160, 76, 217, 93, "white", 7),    # RPM 6720
    (133, 105, 234, 152, "bright", 9), # speed 138
    (230, 193, 299, 210, "white", 7),  # SPORT
]
mask = np.zeros((H, W), np.uint8)
for x0, y0, x1, y1, k, dil in MASKS:
    X0, Y0, X1, Y1 = [int(round(v * s)) for v in (x0, y0, x1, y1)]
    m = kind_mask(full[Y0:Y1, X0:X1], k).astype(np.uint8) * 255
    m = cv2.dilate(m, np.ones((dil, dil), np.uint8))
    mask[Y0:Y1, X0:X1] |= m
# gear "4": red glyph inside the slanted red frame -> polygon so the frame is never touched
gp = (np.array([(161, 175), (205, 175), (199, 209), (147, 209)], float) * s).astype(np.int32)
poly = np.zeros((H, W), np.uint8); cv2.fillPoly(poly, [gp], 255)
r_, g_ = full[..., 0].astype(int), full[..., 1].astype(int)
gm = (((r_ > 90) & (r_ > g_ + 40)).astype(np.uint8) * 255) & poly
mask |= cv2.dilate(gm, np.ones((7, 7), np.uint8)) & poly
clean = cv2.inpaint(np.ascontiguousarray(full), mask, 9, cv2.INPAINT_TELEA)

# ---- 2. downscale ------------------------------------------------------------------------------
lit = np.asarray(Image.fromarray(clean).resize((320, 240), Image.LANCZOS)).astype(float)

# ---- 3. band geometry --------------------------------------------------------------------------
yy, xx = np.mgrid[0:240, 0:320]
rr = np.hypot(xx - CX, yy - CY)
aa = np.degrees(np.arctan2(xx - CX, -(yy - CY)))
band = (rr >= R_IN) & (rr <= R_OUT) & (aa >= A0 - 4) & (aa <= A1 + 4)

# unlit plate (clean off track) + fully lit band: drawn procedurally over the whole sweep,
# the mockup's own partial arc is painted out -- see tools/racecode_arc.py
import os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from racecode_arc import build_arc
unlit, litband = build_arc(lit, CX, CY, R_IN, R_OUT, A0, A1)

unlit8 = np.clip(unlit, 0, 255).astype(np.uint8)
lit8 = np.clip(litband, 0, 255).astype(np.uint8)
lit8[~band] = unlit8[~band]
Image.fromarray(unlit8).save("tools/art/racecode_plate.png")
Image.fromarray(lit8).save("tools/art/racecode_lit.png")

# ---- 4. header ---------------------------------------------------------------------------------
def to565(p):
    return ((int(p[0]) >> 3) << 11) | ((int(p[1]) >> 2) << 5) | (int(p[2]) >> 3)

diff = np.any(lit8 != unlit8, -1)
ys, xs = np.nonzero(diff)
bx0, by0, bx1, by1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
bw, bh = bx1 - bx0, by1 - by0

def emit(name, arr):
    flat = [to565(p) for p in arr.reshape(-1, 3)]
    out = [f"static const uint16_t {name}[{len(flat)}] = {{"]
    for i in range(0, len(flat), 16):
        out.append("  " + ",".join("0x%04X" % v for v in flat[i:i + 16]) + ",")
    out.append("};")
    return out

lines = ["// bg_racecode: RACE CODE plate (rev arc off) + lit arc band. Generated by",
         "// tools/gen_racecode_plate.py, do not edit.",
         "#pragma once", "#include <stdint.h>", "",
         f"static const float RC_CX = {CX}f, RC_CY = {CY}f;",
         f"static const int   RC_R_IN = {R_IN}, RC_R_OUT = {R_OUT};",
         f"static const float RC_A0 = {A0}f, RC_A1 = {A1}f;",
         f"static const int   RC_LIT_X = {bx0}, RC_LIT_Y = {by0}, RC_LIT_W = {bw}, RC_LIT_H = {bh};", ""]
lines += emit("bg_racecode", unlit8)
lines += [""] + emit("bg_racecode_lit", lit8[by0:by1, bx0:bx1])
open(OUT_H, "w").write("\n".join(lines) + "\n")
print("band bbox", bx0, by0, bw, bh)
